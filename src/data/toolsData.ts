const calculateScore = (
  launch: number,
  social: number,
  search: number,
  adoption: number,
  quality: number
): number => {
  return Math.round(
    launch * 0.3 +
    social * 0.25 +
    search * 0.2 +
    adoption * 0.15 +
    quality * 0.1
  );
};

